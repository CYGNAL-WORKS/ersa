#!/usr/bin/env node
// Writes the string catalog as prose (docs/design/CONTENT.md, "The string
// catalog", Text export), so a copy change reads as text in review and Vale,
// which never reads string literals in code, can lint it.
//
//   node scripts/gen-catalog.mjs          write src/catalog/en-US.gen.md
//   node scripts/gen-catalog.mjs --check  fail if that file is stale
//
// Each area is a heading, each key a heading set in code, then its text; a
// plural's forms each sit under their category, also set in code, so Vale can
// skip every heading and read only the copy.
//
// It loads en-US.ts directly: Node strips its types, which is why that module
// holds plain data and imports nothing at runtime.

import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { enUS } from "../src/catalog/en-US.ts";

const SHELL = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(SHELL, "src", "catalog", "en-US.gen.md");

const isPlural = (entry) => typeof entry === "object" && typeof entry.other === "string";

// The lines for one area's keys, depth first in the module's order.
function entries(section, path) {
  return Object.entries(section).flatMap(([name, entry]) => {
    const key = [...path, name].join(".");
    if (typeof entry === "string") return ["", `### \`${key}\``, "", entry];
    if (isPlural(entry)) {
      return ["", `### \`${key}\``, ...Object.entries(entry).flatMap(([category, text]) => ["", `#### \`${category}\``, "", text])];
    }
    return entries(entry, [...path, name]);
  });
}

/** The text export of a catalog, as the file holds it. */
export function markdown(catalog) {
  const lines = [
    "<!-- Generated by apps/shell/scripts/gen-catalog.mjs from en-US.ts. Edit that module, then run the script. -->",
    "",
    "# String catalog: US English",
  ];
  for (const [area, section] of Object.entries(catalog)) {
    lines.push("", `## \`${area}\``, ...entries(section, [area]));
  }
  return lines.join("\n") + "\n";
}

/** Whether the file at `path` holds the export of `catalog`; line endings don't count. */
export function isCurrent(catalog, path) {
  try {
    return readFileSync(path, "utf8").replace(/\r\n/g, "\n") === markdown(catalog);
  } catch (error) {
    // Only a missing file is stale; a locked or unreadable one is reported as itself.
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

// Run only as a script, so the test can import the functions above.
// Both sides as the file system's own real path: argv keeps a junction, a
// symlink and the case it was typed in, and import.meta.url need not match it,
// so a plain comparison would skip --check and pass without checking.
if (process.argv[1] && realpathSync.native(fileURLToPath(import.meta.url)) === realpathSync.native(process.argv[1])) {
  if (!isCurrent(enUS, OUT)) {
    if (process.argv.includes("--check")) {
      console.error("Stale src/catalog/en-US.gen.md. Run `pnpm gen` in apps/shell and commit the result.");
      process.exit(1);
    }
    writeFileSync(OUT, markdown(enUS));
  }
}
