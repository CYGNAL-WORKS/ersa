#!/usr/bin/env node
// Generates the Interface's TypeScript types from the two protocol schemas
// (ARCH-CORE: the Interface depends on Core only through generated types).
//
//   node scripts/gen-types.mjs          write src/protocol/*.gen.ts
//   node scripts/gen-types.mjs --check  fail if those files are stale
//
// Every `$defs` entry becomes an exported type. For the Core API it also
// writes `CoreApiMethods`, mapping each method to its params and result types,
// and `CoreApiNotifications`, mapping each notification to its params, from the
// schema's `<method>.params`, `<method>.result` and `<method>.notification`
// naming convention.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const SHELL = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS = join(SHELL, "..", "..", "protocol", "schema");
const OUT = join(SHELL, "src", "protocol");
const CHECK = process.argv.includes("--check");

const HEADER = "// Generated by scripts/gen-types.mjs from protocol/schema. Do not edit; run `pnpm gen`.\n";

// `core.hello.params` -> `CoreHelloParams`.
const typeName = (key) =>
  key
    .split(/[._-]/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");

// Wraps the schema so every `$defs` entry is reachable and gets its own
// named type, rather than only those the root `$ref` happens to reach.
// `tsType` keeps a cross-file reference as an import instead of inlining the
// other schema.
function wrapped(schema, external) {
  const defs = {};
  for (const [key, def] of Object.entries(schema.$defs)) defs[key] = { ...def, title: typeName(key) };
  const rewritten = JSON.parse(JSON.stringify(defs), (k, v) => {
    if (v && typeof v === "object" && typeof v.$ref === "string" && !v.$ref.startsWith("#")) {
      const [file, pointer] = v.$ref.split("#");
      const ext = external[file];
      if (!ext) throw new Error(`no external schema registered for ${v.$ref}`);
      // `/$defs/session.state/properties/state` -> `AgentEvents.SessionState["state"]`.
      const parts = pointer.split("/").slice(1);
      if (parts[0] !== "$defs" || parts.length % 2 !== 0) throw new Error(`cannot type ${v.$ref}`);
      let type = `${ext.ns}.${typeName(parts[1])}`;
      for (let i = 2; i < parts.length; i += 2) {
        if (parts[i] !== "properties") throw new Error(`cannot type ${v.$ref}`);
        type = `${type}[${JSON.stringify(parts[i + 1])}]`;
      }
      return { tsType: type };
    }
    return v;
  });
  return {
    title: "Root",
    type: "object",
    additionalProperties: false,
    $defs: rewritten,
    properties: Object.fromEntries(Object.keys(rewritten).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  };
}

async function generate(file, external = {}) {
  const schema = JSON.parse(readFileSync(join(SCHEMAS, file), "utf8"));
  let ts = await compile(wrapped(schema, external), "Root", {
    bannerComment: "",
    additionalProperties: false,
    format: true,
    strictIndexSignatures: true,
    cwd: SCHEMAS,
  });
  // The wrapper exists only to reach every definition.
  ts = ts.replace(/export interface Root \{[\s\S]*?\n\}\n/, "");
  // A definition that is only a `$ref` to another (`project.add.result` is a
  // `project`) gets no type of its own from the compiler; alias it.
  for (const [key, def] of Object.entries(schema.$defs)) {
    const name = typeName(key);
    if (new RegExp(`export (type|interface) ${name}\\b`).test(ts)) continue;
    if (typeof def.$ref !== "string" || !def.$ref.startsWith("#/$defs/")) {
      throw new Error(`${file}: no type generated for ${key}`);
    }
    ts += `export type ${name} = ${typeName(def.$ref.slice("#/$defs/".length))};\n`;
  }
  return { schema, ts };
}

const events = await generate("agent-events.schema.json");
const coreApi = await generate("core-api.schema.json", {
  "agent-events.schema.json": { ns: "AgentEvents" },
});

const keys = Object.keys(coreApi.schema.$defs);
const methods = keys.filter((k) => k.endsWith(".params")).map((k) => k.slice(0, -".params".length));
const notifications = keys.filter((k) => k.endsWith(".notification")).map((k) => k.slice(0, -".notification".length));
const methodMap = methods
  .map((m) => `  "${m}": { params: ${typeName(`${m}.params`)}; result: ${typeName(`${m}.result`)} };`)
  .join("\n");
const notificationMap = notifications.map((n) => `  "${n}": ${typeName(`${n}.notification`)};`).join("\n");

const files = {
  "agent-events.gen.ts": `${HEADER}\n${events.ts}`,
  "core-api.gen.ts": [
    HEADER,
    `import type * as AgentEvents from "./agent-events.gen";\n`,
    `/** The Core API version these types describe (the schema's \`x-api-version\`). */`,
    `export const CORE_API_VERSION = ${coreApi.schema["x-api-version"]};\n`,
    coreApi.ts,
    `/** Every Core API method with its params and result types. */`,
    `export interface CoreApiMethods {\n${methodMap}\n}\n`,
    `/** Every notification Core sends, with its params type. */`,
    `export interface CoreApiNotifications {\n${notificationMap}\n}\n`,
  ].join("\n"),
};

let stale = [];
mkdirSync(OUT, { recursive: true });
for (const [name, text] of Object.entries(files)) {
  const path = join(OUT, name);
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  // Compare without line endings, which git may convert on Windows checkouts.
  if (current?.replace(/\r\n/g, "\n") === text) continue;
  if (CHECK) stale.push(name);
  else writeFileSync(path, text);
}
if (stale.length) {
  console.error(`Stale generated types: ${stale.join(", ")}. Run \`pnpm gen\` in apps/shell and commit the result.`);
  process.exit(1);
}
